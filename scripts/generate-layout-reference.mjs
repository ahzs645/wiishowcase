import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MENU_LAYOUT as layout } from "../src/layout/menu.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
await fs.access(path.join(root, layout.clock.fontAsset));
const read = async (name) =>
  JSON.parse(await fs.readFile(path.join(root, "docs", name), "utf8"));
const [manifest, sizing] = await Promise.all([
  read(layout.evidence.references),
  read("interface-sizing/comparison.json"),
]);
const escape = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const declarations = (values) =>
  Object.entries(values)
    .map(([key, value]) => `  --layout-${kebab(key)}: ${value};`)
    .join("\n");
const css = `/* Generated by npm run build:layout from src/layout/menu.js. Do not edit. */
.wii {
  --layout-frame-height: ${layout.coordinates.height};
  --layout-grid-columns: ${layout.grid.columns};
  --layout-date-font-family: "${layout.clock.fontFamily}";
${declarations(layout.tokens.common)}
}
.wii-169 {
${declarations(layout.tokens.modes["16:9"])}
}
/* OFL Latin subset; approximates native Rodin. */
@font-face {
  font-family: "${layout.clock.fontFamily}";
  src: url("/${layout.clock.fontAsset.replace(/^public\//, "")}") format("woff");
  font-weight: ${layout.tokens.common.dateFontWeight};
  font-style: normal;
  font-display: swap;
}
`;

// Validate evidence joins rather than copying independent measurement values
// into the runtime registry. A stale/misspelled source ID must fail the build.
const references = layout.evidence.referenceIds.map((id) => {
  const ref = manifest.references.find((item) => item.id === id);
  if (!ref) throw new Error(`Unknown layout reference: ${id}`);
  return ref;
});
for (const evidence of [
  layout.evidence.research,
  layout.evidence.measurements,
  ...layout.anchors.flatMap((a) => a.evidence),
]) {
  await fs.access(path.join(root, "docs", evidence));
}
const screens = [...new Set(sizing.entries.map((entry) => entry.id))].map(
  (id) => {
    const entries = sizing.entries.filter((entry) => entry.id === id);
    return {
      id,
      title: entries[0].title,
      layoutStatus: id.startsWith("menu-")
        ? "Shared menu registry"
        : "Local rules; registry adapter pending",
      implementation: id.startsWith("menu-")
        ? "src/layout/menu.js"
        : "src/system-interface.css and screen component",
      references: [
        ...new Set(entries.map((entry) => entry.reference?.id).filter(Boolean)),
      ],
      captures: entries.map(({ mode, width, height }) => ({
        mode,
        width,
        height,
      })),
      viewer: `../interface-sizing/?interface=${encodeURIComponent(id)}`,
    };
  },
);
const link = (url, label) => `<a href="${escape(url)}">${escape(label)}</a>`;
const table = (headers, rows) =>
  `<div class="table-scroll"><table><thead><tr>${headers.map((h) => `<th>${escape(h)}</th>`).join("")}</tr></thead><tbody>${rows.map((row) => `<tr>${row.map((cell) => `<td>${cell}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`;
const wide = { ...layout.tokens.common, ...layout.tokens.modes["16:9"] };
const rows = Object.entries(layout.tokens.common).map(([name, value]) => [
  `<code>${escape(name)}</code>`,
  String(value),
  String(wide[name]),
  name.endsWith("Percent")
    ? "%"
    : name.endsWith("Weight")
      ? "font weight"
      : "480-line units",
]);
rows.push([
  "<code>sdCenterPercent</code>",
  "— (sdLeft anchor)",
  String(wide.sdCenterPercent),
  "% of frame width",
]);
const html = `<!doctype html>
<html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Wii interface layout reference</title>
<style>
body{margin:0;background:#f7f9fc;color:#203040;font:16px/1.5 system-ui,sans-serif}main{max-width:1150px;margin:auto;padding:28px}h1{font-size:30px}h2{margin-top:32px}a{color:#075ca6}code{font-size:14px}table{border-collapse:collapse;width:100%;background:white}th,td{text-align:left;vertical-align:top;border:1px solid #d4dce6;padding:9px}th{background:#eaf0f6}.table-scroll{overflow-x:auto}.note{padding:16px;background:#e8f3ff;border-left:4px solid #2085c0}input{font:inherit;padding:9px;max-width:100%;box-sizing:border-box}nav{display:flex;gap:18px;flex-wrap:wrap}li{margin:6px 0}
</style><main>
<h1>Wii interface layout reference</h1>
<p>One maintained implementation registry for menu positions, sizing and regional behavior, with links to independent evidence and other interface screens.</p>
<nav>${link("#positions", "Positions and sizes")}${link("#sources", "Source confidence")}${link("#screens", "Screen index")}${link("../layout-reference.md", "Maintenance guide")}${link("menu-registry.json", "Machine-readable registry")}</nav>
<p class="note">${escape(layout.target)}. ${escape(layout.evidence.confidence)} Other screens are indexed below; their layout adapters are still pending.</p>
<h2>Coordinate contract</h2>
<p>${escape(layout.coordinates.origin)}. ${escape(layout.coordinates.scaling)}. Base frames: 640×480 (4:3) and 853⅓×480 (16:9). Capture/test sizes: ${layout.coordinates.captureSizes.map((s) => s.join("×")).join(", ")}. ${escape(layout.coordinates.note)}</p>
<p>A logical slot rectangle, masked border, SVG glyph and button hit area are different bounds. Compare like bounds. Preserve source aspect/crop and record capture state before fitting geometry.</p>
<h2 id="positions">Menu positions and sizes</h2>
${table(["Token", "4:3", "16:9", "Unit"], rows)}
<h2>Anchors and derived placement</h2>
${table(
  ["Area", "Placement rule", "Evidence / limitations"],
  layout.anchors.map((a) => [
    escape(a.id),
    escape(a.rule),
    `${a.evidence.map((e) => link(`../${e}`, e)).join("<br>")}<p>${escape(a.note)}</p>`,
  ]),
)}
<p>Grid: ${layout.grid.columns} columns × ${layout.grid.rows} rows × ${layout.grid.pages} pages = ${layout.grid.columns * layout.grid.rows * layout.grid.pages} slots. The curve uses depth ${layout.curve.depth}, height divisor ${layout.curve.scaleHeight}, width fractions ${layout.curve.flatWidthFraction}/${layout.curve.bendWidthFraction}, Bézier controls ${layout.curve.controlNear}/${layout.curve.controlFar} and stroke ${layout.curve.strokeWidth}. ${escape(layout.curve.note)}</p>
<h2>Fonts and clock panes</h2>
<p>${escape(layout.clock.fontStatus)} Font asset: <code>${escape(layout.clock.fontAsset)}</code>. ${layout.clock.cells} clock cells, digit advance ${layout.clock.digitAdvance}, colon advance ${layout.clock.colonAdvance}, trailing trim ${layout.clock.trailingTrim}, SVG height ${layout.clock.viewBoxHeight}. The hour tens cell stays allocated when blank.</p>
${table(
  [
    "Region",
    "Hour cycle / zero hour",
    "Period position",
    "Current English date",
  ],
  Object.entries(layout.clock.regions).map(([id, p]) => [
    id,
    `${p.hourCycle} / ${p.zeroHour}`,
    escape(p.periodSide ?? "none"),
    `${escape(p.dateOrder)}; ${p.datePadding ? "padded" : "unpadded"}`,
  ]),
)}
<p>${escape(layout.clock.localizationNote)} Country inference is a compatibility fallback; explicit <code>settings.menuRegion</code> takes priority.</p>
<h2>Firmware and platform profiles</h2>
${table(
  ["Profile", "Status", "Scope"],
  layout.profiles.map((p) => [escape(p.id), escape(p.status), escape(p.note)]),
)}
<h2 id="sources">Source confidence</h2>
${table(
  [
    "Reference",
    "Original dimensions / hash",
    "Firmware and capture confidence",
  ],
  references.map((r) => [
    link(r.sourceURL, r.title),
    `${r.originalSize.join("×")}<br><code>${escape(r.originalSHA256)}</code>`,
    `${escape(r.systemMenu?.exactVersion ?? "Exact firmware unknown")}<br>${escape(r.systemMenu?.confidence ?? r.notes)}<p>${escape(r.notes)}</p>`,
  ]),
)}
<p>${link("../menu-versions/", "Open independent overlays and measurements")} · ${link("../menu-versions.md", "Version/region research")} · ${link("../interface-audit/references.json", "Complete source manifest")}</p>
<h2>Capture state to record</h2><p>${layout.captureStateFields.map(escape).join("; ")}.</p>
<h2 id="screens">All recorded interface screens</h2>
<p>This index is generated from the system-sizing comparison manifest. It records available captures, references and layout ownership, not an overall fidelity rating. Full channel application layouts remain separate from the menu shell.</p>
<label>Find a screen <input id="filter" type="search" placeholder="Settings, keyboard, message…"></label>
<div id="screen-table">${table(
  ["Screen", "Layout ownership", "References", "Recorded captures"],
  screens.map((s) => [
    link(s.viewer, s.title),
    escape(s.layoutStatus),
    s.references.map(escape).join(", ") || "—",
    s.captures.map((c) => `${c.mode}: ${c.width}×${c.height}`).join("<br>"),
  ]),
)}</div>
<h2>Remaining gaps</h2><ul>${layout.gaps.map((g) => `<li>${escape(g)}</li>`).join("")}</ul>
<p>Generated from <code>src/layout/menu.js</code> and evidence manifests with <code>npm run build:layout</code>. ${link("screen-index.json", "Download screen index")}. ${link("../layout-reference.md", "How to update or add an adapter")}.</p>
</main><script>document.querySelector('#filter').addEventListener('input',e=>{const q=e.target.value.toLowerCase();for(const row of document.querySelectorAll('#screen-table tbody tr'))row.hidden=!row.textContent.toLowerCase().includes(q)});</script></html>
`;
const outputs = {
  "src/layout/menu.generated.css": css,
  "docs/layout-reference/menu-registry.json":
    JSON.stringify(layout, null, 2) + "\n",
  "docs/layout-reference/screen-index.json":
    JSON.stringify({ screens }, null, 2) + "\n",
  "docs/layout-reference/index.html": html,
};
for (const [relative, contents] of Object.entries(outputs)) {
  const filename = path.join(root, relative);
  if (process.argv.includes("--check")) {
    if ((await fs.readFile(filename, "utf8")) !== contents)
      throw new Error(`${relative} is stale; run npm run build:layout`);
  } else {
    await fs.mkdir(path.dirname(filename), { recursive: true });
    await fs.writeFile(filename, contents);
  }
}
console.log(
  `${process.argv.includes("--check") ? "Checked" : "Generated"} menu layout tokens and reference; ${screens.length} screens indexed.`,
);
